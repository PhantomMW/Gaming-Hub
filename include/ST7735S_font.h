/* =========================================================
 * Character Index
 * ========================================================= */

static uint8_t ST7735S_FontGetIndex(
    char Copy_cCharacter
)
{
    /* Space */
    if (Copy_cCharacter == ' ')
    {
        return 0U;
    }

    /* > */
    if (Copy_cCharacter == '>')
    {
        return 1U;
    }

    /* Numbers */
    if (
        (Copy_cCharacter >= '0') &&
        (Copy_cCharacter <= '9')
    )
    {
        return (uint8_t)
               (2U + (Copy_cCharacter - '0'));
    }

    /* Capital Letters */
    if (
        (Copy_cCharacter >= 'A') &&
        (Copy_cCharacter <= 'Z')
    )
    {
        return (uint8_t)
               (12U + (Copy_cCharacter - 'A'));
    }

    /* Unsupported character */
    return 0U;
}


